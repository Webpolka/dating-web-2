// lib/pluralize.ts
//
// Утилита для склонения русских существительных по числу.
// Используется в местах, где нужно показать "N год/года/лет" или "N человек/человека".
//
// ПРАВИЛА РУССКОГО ЯЗЫКА:
//   1, 21, 31, 41... (заканчивается на 1, кроме 11) → 1 форма ("год")
//   2, 3, 4, 22, 23, 24... (заканчивается на 2-4, кроме 12-14) → 2 форма ("года")
//   0, 5-20, 25-30... (всё остальное) → 3 форма ("лет")
//
// ПРИМЕРЫ:
//   pluralizeRu(1, ['год', 'года', 'лет'])    → 'год'    → "1 год"
//   pluralizeRu(2, ['год', 'года', 'лет'])    → 'года'   → "2 года"
//   pluralizeRu(5, ['год', 'года', 'лет'])    → 'лет'    → "5 лет"
//   pluralizeRu(11, ['год', 'года', 'лет'])   → 'лет'    → "11 лет"
//   pluralizeRu(21, ['год', 'года', 'лет'])   → 'год'    → "21 год"
//   pluralizeRu(22, ['год', 'года', 'лет'])   → 'года'   → "22 года"
//   pluralizeRu(25, ['год', 'года', 'лет'])   → 'лет'    → "25 лет"
//   pluralizeRu(43, ['год', 'года', 'лет'])   → 'года'   → "43 года"
//
// ДЛЯ ДРУГИХ СЛОВ — просто меняешь массив forms:
//   pluralizeRu(2, ['человек', 'человека', 'человек']) → 'человека' → "2 человека"
//   pluralizeRu(5, ['сообщение', 'сообщения', 'сообщений']) → 'сообщений'
//   pluralizeRu(1, ['подарок', 'подарка', 'подарков']) → 'подарок'

/**
 * Склоняет русское существительное по числу.
 *
 * @param count — число (например возраст, количество сообщений, подарков)
 * @param forms — массив из 3 форм: [для 1, для 2-4, для 5+ / 0 / 11-14]
 * @returns слово в правильной форме (без числа)
 *
 * @example
 * pluralizeRu(43, ['год', 'года', 'лет']) // → 'года'
 * pluralizeRu(21, ['год', 'года', 'лет']) // → 'год'
 * pluralizeRu(5, ['год', 'года', 'лет'])  // → 'лет'
 */
export function pluralizeRu(
  count: number,
  forms: [string, string, string],
): string {
  // Защита от NaN / undefined / null — на всякий случай возвращаем 3 форму
  if (!Number.isFinite(count)) return forms[2];

  const mod10 = Math.abs(count) % 10;
  const mod100 = Math.abs(count) % 100;

  // Особый случай: 11-14 → 3 форма ("лет", "человек")
  // Покрывает: 11, 12, 13, 14, 111, 112, 113, 114, 211, 212, ...
  if (mod100 >= 11 && mod100 <= 14) {
    return forms[2];
  }

  // Заканчивается на 1 (но не 11) → 1 форма ("год")
  // Покрывает: 1, 21, 31, 41, 51, 61, 71, 81, 91, 101, ...
  if (mod10 === 1) {
    return forms[0];
  }

  // Заканчивается на 2-4 (но не 12-14) → 2 форма ("года")
  // Покрывает: 2, 3, 4, 22, 23, 24, 32, 33, 34, ...
  if (mod10 >= 2 && mod10 <= 4) {
    return forms[1];
  }

  // Всё остальное → 3 форма ("лет")
  // Покрывает: 0, 5, 6, 7, 8, 9, 10, 15, 16, 17, 18, 19, 20, 25, 26, ...
  return forms[2];
}

/**
 * Форматирует число с правильным словом — "43 года", "21 год", "5 лет".
 * Convenience-обёртка над pluralizeRu.
 *
 * @example
 * formatWithWord(43, ['год', 'года', 'лет']) // → '43 года'
 * formatWithWord(21, ['год', 'года', 'лет']) // → '21 год'
 */
export function formatWithWord(
  count: number,
  forms: [string, string, string],
): string {
  return `${count} ${pluralizeRu(count, forms)}`;
}
