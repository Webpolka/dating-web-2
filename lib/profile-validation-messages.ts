// ============================================================
// Карта типовых правил Laravel → фиксированные человекочитаемые сообщения.
//
// FIX: раньше был generic regex /^Поле\s+\S+\s+(.+)$/ — он ломается на составных
// именах полей: если Laravel выводит "Поле Учеб. год должно быть не меньше 1950."
// или "Поле institution year должно быть..." — то \S+ хватает только первое слово
// (например "Учеб." или "institution"), а второе слово попадает в "тело" → получается
// мусор типа "ер Year должно быть не меньше 1950." или "год должно быть не меньше 1950."
//
// НОВАЯ СТРАТЕГИЯ: для каждого типового правила (required, integer, min, max, ...)
// определяем его по КЛЮЧЕВОМУ СЛОВУ в сообщении, и подставляем фиксированный
// человекочитаемый текст. Не зависит от того, как отформатировано имя поля.
//
// Каждое правило: { pattern, message }.
//   - pattern: regex ищет ключевую фразу в сообщении (например "должно быть не меньше")
//   - message: функция, возвращает готовый текст (с подстановкой чисел из regex-групп)
// ============================================================
type ErrorRule = {
  pattern: RegExp;
  message: (match: RegExpMatchArray) => string;
};

const ERROR_RULES: ErrorRule[] = [
  // required / filled
  // "Поле <field> обязательно для заполнения."
  {
    pattern: /обязательно для заполнения/i,
    message: () => 'Обязательное поле',
  },
  // integer
  // "Поле <field> должно быть целым числом."
  {
    pattern: /должно быть целым числом/i,
    message: () => 'Должно быть целым числом',
  },
  // numeric
  // "Поле <field> должно быть числом."
  {
    pattern: /должно быть числом/i,
    message: () => 'Должно быть числом',
  },
  // string
  // "Поле <field> должно быть строкой."
  {
    pattern: /должно быть строкой/i,
    message: () => 'Должно быть строкой',
  },
  // array
  // "Поле <field> должно быть массивом."
  {
    pattern: /должно быть массивом/i,
    message: () => 'Должно быть массивом',
  },
  // min (numeric): "должно быть не меньше 1950" → "Должно быть не меньше 1950"
  {
    pattern: /должно быть не меньше\s+(\d+)/i,
    message: (m) => `Должно быть не меньше ${m[1]}`,
  },
  // gte (numeric): "должно быть :value или больше" — редко, но пусть будет
  {
    pattern: /должно быть\s+(\d+)\s+или больше/i,
    message: (m) => `Должно быть ${m[1]} или больше`,
  },
  // max (numeric): "должно быть не больше 300" → "Должно быть не больше 300"
  {
    pattern: /должно быть не больше\s+(\d+)/i,
    message: (m) => `Должно быть не больше ${m[1]}`,
  },
  // lte (numeric): "должно быть не больше :value"
  // между X и Y
  // between (numeric): "должно быть от 50 до 300" → "Должно быть от 50 до 300"
  {
    pattern: /должно быть от\s+(\d+)\s+до\s+(\d+)/i,
    message: (m) => `Должно быть от ${m[1]} до ${m[2]}`,
  },
  // min (string): "должно содержать минимум 5 символов" → "Минимум 5 символов"
  {
    pattern: /должно содержать минимум\s+(\d+)\s+символов/i,
    message: (m) => `Минимум ${m[1]} символов`,
  },
  // max (string): "не может содержать больше 200 символов" → "Максимум 200 символов"
  {
    pattern: /не может содержать больше\s+(\d+)\s+символов/i,
    message: (m) => `Максимум ${m[1]} символов`,
  },
  // between (string): "должно содержать от 5 до 200 символов" → "От 5 до 200 символов"
  {
    pattern: /должно содержать от\s+(\d+)\s+до\s+(\d+)\s+символов/i,
    message: (m) => `От ${m[1]} до ${m[2]} символов`,
  },
  // size (string): "должно содержать 5 символов" → "Должно быть 5 символов"
  {
    pattern: /должно содержать\s+(\d+)\s+символов/i,
    message: (m) => `Должно быть ${m[1]} символов`,
  },
  // email
  // "Поле <field> должно быть корректным email-адресом."
  {
    pattern: /должно быть корректным\s*email/i,
    message: () => 'Введите корректный email',
  },
  // url
  // "Поле <field> должно быть корректным URL."
  {
    pattern: /должно быть корректным\s*url/i,
    message: () => 'Введите корректный URL',
  },
  // date
  // "Поле <field> должно быть корректной датой."
  {
    pattern: /должно быть корректной датой/i,
    message: () => 'Введите корректную дату',
  },
  // in / exists / enum
  // "Выбранное значение для <field> некорректно."
  {
    pattern: /Выбранное значение для\s+\S[\S\s]*?некорректно/i,
    message: () => 'Выбрано некорректное значение',
  },
  // unique
  // "Такое значение поля <field> уже существует."
  {
    pattern: /Такое значение поля\s+\S[\S\s]*?уже существует/i,
    message: () => 'Такое значение уже существует',
  },
  // regex / format
  // "Формат поля <field> некорректен." → "Некорректный формат"
  {
    pattern: /Формат поля\s+\S[\S\s]*?некорректен/i,
    message: () => 'Некорректный формат',
  },
  // image
  // "Поле <field> должно быть изображением."
  {
    pattern: /должно быть изображением/i,
    message: () => 'Файл должен быть изображением',
  },
  // mimes / mimetypes
  // "Поле <field> должно быть файлом типа: :values."
  {
    pattern: /должно быть файлом типа/i,
    message: () => 'Неверный тип файла',
  },
];

// ============================================================
// Применяет правила к тексту ошибки.
// Возвращает человекочитаемое сообщение.
//
// Алгоритм:
//   1. Идём по списку ERROR_RULES по очереди.
//   2. Если regex совпал — возвращаем message(match) (фиксированный текст).
//   3. Если ни одно правило не сработало — fallback:
//      отрезаем "Поле " + первый токен, возвращаем остаток с большой буквы.
//      Это покрывает редкие правила, для которых мы не сделали конкретный шаблон.
// ============================================================
function cleanMessage(raw: string): string {
  const text = raw.trim();

  // 1. Пробуем типовые правила
  for (const rule of ERROR_RULES) {
    const match = text.match(rule.pattern);
    if (match) {
      return rule.message(match);
    }
  }

  // 2. Fallback: отрезаем "Поле " + первый токен (одно слово до пробела).
  //    Остальное возвращаем с большой буквы.
  //    Это покрывает редкие правила. Если имя поля составное (через пробел) —
  //    fallback может сработать неточно, но это лучше, чем оставить "Поле institution_year..."
  const fallbackMatch = text.match(/^Поле\s+\S+\s+(.+)$/i);
  if (fallbackMatch) {
    const body = fallbackMatch[1].trim();
    if (body.length > 0) {
      return body.charAt(0).toUpperCase() + body.slice(1);
    }
  }

  // 3. Совсем fallback — возвращаем как есть
  return text;
}

// ============================================================
// Тип результата humanize — для тоста и инпутов.
// ============================================================
export interface HumanizedError {
  /** Техническое имя поля — для привязки ошибки к инпуту (institution_year). */
  field: string;
  /** Человекочитаемый лейбл поля — для тоста (Год выпуска). */
  label: string;
  /** Очищенное сообщение — для тоста и текста под инпутом. */
  message: string;
  /** Оригинал Laravel-сообщения — на всякий случай для отладки. */
  rawMessage: string;
}

// ============================================================
// Главная функция — принимает Laravel errors объект,
// возвращает массив человекочитаемых ошибок.
//
// Пример входа:
//   {
//     institution_year: ['Поле institution_year должно быть не меньше 1950.'],
//     height: ['Поле height должно быть целым числом.']
//   }
//
// Пример выхода:
//   [
//     { field: 'institution_year', label: 'Год выпуска',
//       message: 'Должно быть не меньше 1950.',
//       rawMessage: 'Поле institution_year должно быть не меньше 1950.' },
//     { field: 'height', label: 'Рост',
//       message: 'Должно быть целым числом.',
//       rawMessage: 'Поле height должно быть целым числом.' }
//   ]
//
// FIX: Laravel возвращает ошибки по элементам массивов в формате
// `dating_goals.0`, `dating_goals.1`, `body_decorations.2` и т.д.
// Раньше лейбл для таких ключей был "dating_goals.1" (raw) — некрасиво в тосте.
// Теперь: если key содержит точку → берём часть до точки, ищем лейбл для неё,
// а индекс (цифра после точки) НЕ показываем (он неинформативен для юзера).
// Пример: dating_goals.1 → лейбл "Цели знакомства" (берём из FIELD_LABELS по
// базовому имени "dating_goals").
// ============================================================
export function humanizeLaravelErrors(
  errors: Record<string, string | string[]>,
): HumanizedError[] {
  const result: HumanizedError[] = [];
  for (const [field, msgs] of Object.entries(errors)) {
    // FIX: если key содержит точку (например "dating_goals.1"),
    // берём часть до точки для поиска лейбла.
    // Базовое имя — это "чистое" имя поля без индекса массива.
    const baseField = field.includes('.')
      ? field.split('.')[0]
      : field;
    const label = FIELD_LABELS[baseField] ?? field;
    const msgArr = Array.isArray(msgs) ? msgs : [String(msgs)];
    for (const raw of msgArr) {
      result.push({
        field,  // field оставляем как есть — для привязки к инпутам (если надо)
        label,
        message: cleanMessage(raw),
        rawMessage: raw,
      });
    }
  }
  return result;
}

// ============================================================
// Хелпер для удобного вывода в тост.
//
// Возвращает массив объектов { label, message } — по одному на каждую ошибку.
// Почему НЕ просто массив строк: в родительском компоненте мы хотим рендерить
// каждую ошибку как JSX <span> с правильной структурой (лейбл — сообщение).
// Возвращаем объекты, чтобы родитель мог сам решить как форматировать.
//
// Формат: лейбл и сообщение разделены тире " — " (НЕ двоеточием).
// Двоеточие выглядит как служебная пунктуация, тире — естественнее читается.
// Пример: "Год выпуска — Должно быть не меньше 1950"
// ============================================================
export interface ToastLine {
  /** Человекочитаемый лейбл поля ("Год выпуска"). */
  label: string;
  /** Человекочитаемое сообщение ("Должно быть не меньше 1950"). */
  message: string;
}

export function formatErrorsForToast(
  errors: Record<string, string | string[]>,
): ToastLine[] {
  return humanizeLaravelErrors(errors).map(e => ({
    label: e.label,
    message: e.message,
  }));
}

// ============================================================
// Хелпер для привязки к инпутам: возвращает объект
// { field: message } — берём первое сообщение для каждого поля.
// Удобно передавать в PersonalInfo как prop.errors.
// ============================================================
export function buildFieldErrors(
  errors: Record<string, string | string[]>,
): Record<string, string> {
  const result: Record<string, string> = {};
  for (const [field, msgs] of Object.entries(errors)) {
    const msgArr = Array.isArray(msgs) ? msgs : [String(msgs)];
    if (msgArr.length > 0) {
      result[field] = cleanMessage(msgArr[0]);
    }
  }
  return result;
}
