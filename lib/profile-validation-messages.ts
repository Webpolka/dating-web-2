// Карта Laravel-ошибок на человекочитаемые сообщения для тостов и инпутов.
//
// ПРОБЛЕМА: Laravel с ru/validation.php отдаёт сообщения вида:
//   "Поле institution_year должно быть не меньше 1950."
//   "Выбранное значение для body_type некорректно."
//   "Поле height обязательно для заполнения."
//
// В этих сообщениях есть СЛУЖЕБНАЯ ИНФА:
//   - слово "Поле" в начале
//   - техническое имя поля (institution_year, body_type) — пользователь не понимает
//   - в середине: "Выбранное значение для X некорректно" — слово "для X" лишнее
//
// РЕШЕНИЕ:
//   1. Для каждого поля у нас есть FIELD_LABELS[field] → "Год выпуска"
//   2. Применяем regex-очистку к тексту Laravel-сообщения:
//      - "Поле <name> <тело>" → "<тело>"  (отрезаем "Поле <name>")
//      - "Выбранное значение для <name> некорректно" → "Выбрано некорректное значение"
//      - "Такое значение поля <name> уже существует" → "Такое значение уже существует"
//   3. Первую букву капитализируем (хотя после отрезания префикса обычно уже с большой)
//   4. Возвращаем { field, label, message } — для тоста и подсветки инпута
//
// ВАЖНО: regex-шаблоны соответствуют РУССКОМУ Laravel-переводу (ru/validation.php).
// Если на бэке меняется локаль — нужно обновить CLEAN_RULES.
//
// Источник ru-переводов: /lang/ru/validation.php на бэке (предоставил братан).

